import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { createStaffMember, fetchStaffManagementOptions } from './staffApi';
import type { StaffMember } from '../types/staff';

const staff: StaffMember = {
  id: 'staff-1',
  name: 'New Carer',
  username: 'test.user',
  email: 'new.carer@example.test',
  phone: null,
  employee_role: 'staff',
  status: 'active',
  employeeNumber: 'WS-0009',
  joinedDate: '27/08/2026',
  avatarUrl: null,
  facilityUuid: 'facility-1',
  facilityName: 'Trinity Central',
  employmentType: 'full-time',
  title: null,
  shiftDetails: null,
};

describe('staffApi account provisioning transport', () => {
  beforeEach(() => {
    vi.stubGlobal('fetch', vi.fn());
  });

  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it('sends the manager create request with cookies and parses the one-time credential result', async () => {
    vi.mocked(fetch).mockResolvedValueOnce({
      ok: true,
      status: 201,
      json: async () => ({ staff, temporaryPassword: 'AutoGenerated1!' }),
    } as Response);

    const result = await createStaffMember({
      name: staff.name,
      email: staff.email,
      facilityUuid: staff.facilityUuid,
      employmentType: staff.employmentType,
      employee_role: staff.employee_role,
      status: staff.status,
    });

    expect(result).toEqual({ staff, temporaryPassword: 'AutoGenerated1!' });
    expect(fetch).toHaveBeenCalledWith(
      expect.stringContaining('/api/admin/staff'),
      expect.objectContaining({ method: 'POST', credentials: 'include' }),
    );
  });

  it('parses real facility and employment options for the existing modal', async () => {
    vi.mocked(fetch).mockResolvedValueOnce({
      ok: true,
      status: 200,
      json: async () => ({
        facilities: [{ id: 'facility-1', name: 'Trinity Central' }],
        employmentTypes: ['full-time', 'part-time'],
      }),
    } as Response);

    await expect(fetchStaffManagementOptions()).resolves.toEqual({
      facilities: [{ id: 'facility-1', name: 'Trinity Central' }],
      employmentTypes: ['full-time', 'part-time'],
    });
  });
});
