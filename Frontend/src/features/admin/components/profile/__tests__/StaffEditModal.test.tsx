import { fireEvent, render, screen } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { StaffEditModal } from '../StaffEditModal';
import type { StaffCreateResult, StaffManagementOptions, StaffMember } from '../../../types/staff';

const STAFF: StaffMember = {
  id: 'staff-1',
  name: 'Bob Staff',
  username: 'test.user',
  email: 'staff@example.test',
  phone: '+64 21 555 0101',
  employee_role: 'staff',
  status: 'active',
  employeeNumber: 'WS-0002',
  joinedDate: '19/05/2024',
  avatarUrl: null,
  facilityUuid: 'facility-1',
  facilityName: 'Trinity Central',
  employmentType: 'full-time',
  title: null,
  shiftDetails: null,
};

const OPTIONS: StaffManagementOptions = {
  facilities: [{ id: 'facility-1', name: 'Trinity Central' }],
  employmentTypes: ['full-time', 'part-time'],
};

const renderModal = (props: Partial<React.ComponentProps<typeof StaffEditModal>> = {}): void => {
  render(
    <StaffEditModal
      isOpen
      staff={null}
      saving={false}
      errorMessage={null}
      isOnlyManager={false}
      options={OPTIONS}
      optionsLoading={false}
      onClose={vi.fn()}
      onSubmit={vi.fn()}
      {...props}
    />,
  );
};

describe('StaffEditModal', () => {
  beforeEach(() => {
    Object.defineProperty(navigator, 'clipboard', {
      configurable: true,
      value: { writeText: vi.fn().mockResolvedValue(undefined) },
    });
  });

  it('creates an employee without a password input and reveals the generated credential once', async () => {
    const onSubmit = vi.fn<(values: unknown) => Promise<StaffCreateResult>>().mockResolvedValue({
      staff: STAFF,
      temporaryPassword: 'AutoGenerated1!',
    });

    renderModal({ onSubmit });

    expect(screen.getByRole('heading', { name: 'Create employee account' })).toBeInTheDocument();
    expect(screen.queryByLabelText(/password/i)).not.toBeInTheDocument();

    fireEvent.change(screen.getByLabelText('Full name'), { target: { value: STAFF.name } });
    fireEvent.change(screen.getByLabelText('Work email'), { target: { value: STAFF.email } });
    fireEvent.change(screen.getByLabelText('Facility'), {
      target: { value: STAFF.facilityUuid },
    });
    fireEvent.change(screen.getByLabelText('Employment type'), {
      target: { value: STAFF.employmentType },
    });
    fireEvent.change(screen.getByLabelText('Employee role'), {
      target: { value: STAFF.employee_role },
    });
    fireEvent.click(screen.getByRole('button', { name: 'Create employee account' }));

    expect(onSubmit).toHaveBeenCalledWith({
      name: STAFF.name,
      email: STAFF.email,
      facilityUuid: STAFF.facilityUuid,
      employmentType: STAFF.employmentType,
      employee_role: STAFF.employee_role,
      status: STAFF.status,
    });
    expect(await screen.findByRole('heading', { name: 'Account created' })).toBeInTheDocument();
    expect(screen.queryByText('AutoGenerated1!')).not.toBeInTheDocument();

    fireEvent.click(screen.getByRole('button', { name: 'Show temporary password' }));
    expect(screen.getByText('AutoGenerated1!')).toBeInTheDocument();
  });

  it('keeps staff-owned profile fields read-only in edit mode', () => {
    renderModal({ staff: STAFF });

    expect(screen.getByRole('heading', { name: 'Employee account settings' })).toBeInTheDocument();
    expect(
      screen.getByText('Personal profile details are managed by the employee.'),
    ).toBeInTheDocument();
    expect(screen.queryByLabelText('Full name')).not.toBeInTheDocument();
    expect(screen.queryByLabelText('Phone')).not.toBeInTheDocument();
    expect(screen.getByText(STAFF.name)).toBeInTheDocument();
    expect(screen.getByText(STAFF.employeeNumber)).toBeInTheDocument();
  });
});
