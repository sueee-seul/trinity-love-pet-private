import { beforeEach, describe, expect, it, vi } from 'vitest';
import { createStaff, removeStaff, updateStaff } from '../repositories/staff.repository.js';

interface QueryResult {
  rows: Array<Record<string, unknown>>;
  rowCount: number;
}

type Query = (sql: string, values?: readonly unknown[]) => Promise<QueryResult>;

type FakeClient = {
  query: ReturnType<typeof vi.fn<Query>>;
  release: ReturnType<typeof vi.fn<() => void>>;
};

const { withDatabaseConnectionMock } = vi.hoisted(() => ({
  withDatabaseConnectionMock: vi.fn(),
}));

vi.mock('../repositories/database.connection.js', () => ({
  withDatabaseConnection: withDatabaseConnectionMock,
}));

const STAFF_UUID = '00000000-0000-4000-8000-000000000201';
const FACILITY_UUID = '00000000-0000-4000-8000-000000000301';
const OTHER_MANAGER_UUID = '00000000-0000-4000-8000-000000000202';

const staffRow = (staffRole = 'staff'): Record<string, unknown> => ({
  uuid: STAFF_UUID,
  legacy_id: null,
  display_name: 'Staff Member',
  username: 'staff.member',
  email: 'staff@example.test',
  phone: '+64 21 555 0000',
  avatar_url: null,
  created_at: new Date('2026-08-26T00:00:00.000Z'),
  staff_role: staffRole,
  staff_status: 'active',
  employee_number: 'WS-0007',
  facility_uuid: FACILITY_UUID,
  facility_name: 'Trinity Central',
  employment_type: 'full-time',
});

const emptyResult = (): QueryResult => ({ rows: [], rowCount: 0 });

const createClient = (
  options: { assignmentRows?: Array<Record<string, unknown>>; staffRole?: string } = {},
): FakeClient => {
  const query = vi.fn<Query>(async (sql: string): Promise<QueryResult> => {
    if (sql === 'BEGIN') {
      return emptyResult();
    }
    if (sql === 'COMMIT') {
      return emptyResult();
    }
    if (sql === 'ROLLBACK') {
      return emptyResult();
    }
    if (sql.includes('SELECT f.uuid')) {
      return { rows: [{ uuid: FACILITY_UUID }], rowCount: 1 };
    }
    if (sql.includes('SELECT MAX(NULLIF')) {
      return { rows: [{ highest: 6 }], rowCount: 1 };
    }
    if (sql.includes('SELECT 1 FROM users WHERE username')) {
      return emptyResult();
    }
    if (sql.includes('SELECT COUNT(*)::text')) {
      return { rows: [{ count: '1' }], rowCount: 1 };
    }
    if (sql.includes('SELECT uuid') && sql.includes('FROM employee_assignments')) {
      const rows = options.assignmentRows ?? [];
      return { rows, rowCount: rows.length };
    }
    if (sql.includes('SELECT u.uuid')) {
      return { rows: [staffRow(options.staffRole)], rowCount: 1 };
    }
    // Another manager exists, so a manager may be removed.
    if (sql.includes('SELECT users_uuid') && sql.includes('FROM employees')) {
      return { rows: [{ users_uuid: OTHER_MANAGER_UUID }], rowCount: 1 };
    }
    if (sql.includes('INSERT INTO users')) {
      return { rows: [{ uuid: STAFF_UUID }], rowCount: 1 };
    }
    if (sql.includes('DELETE FROM users')) {
      return emptyResult();
    }
    return emptyResult();
  });

  const release = vi.fn<() => void>();
  return { query, release };
};

const configureDatabase = (client: ReturnType<typeof createClient>): void => {
  withDatabaseConnectionMock.mockImplementationOnce(
    async (work: (databaseClient: typeof client) => Promise<unknown>): Promise<unknown> => {
      try {
        return await work(client);
      } finally {
        client.release();
      }
    },
  );
};

describe('staff repository transaction boundaries', () => {
  beforeEach(() => {
    withDatabaseConnectionMock.mockReset();
  });

  it('commits staff creation after both user and employee rows are written', async () => {
    const client = createClient();
    configureDatabase(client);

    const result = await createStaff({
      name: 'Staff Member',
      email: 'staff@example.test',
      facilityUuid: FACILITY_UUID,
      employmentType: 'full-time',
      employee_role: 'staff',
      status: 'active',
      temporaryPassword: 'AutoGenerated1!',
    });

    expect(result.outcome).toBe('created');
    expect(client.query).toHaveBeenCalledWith('BEGIN');
    expect(client.query).toHaveBeenCalledWith('COMMIT');
    const statements = client.query.mock.calls.map(([query]) => String(query));
    expect(statements.indexOf('BEGIN')).toBeLessThan(
      statements.findIndex((query) => query.includes('pg_advisory_xact_lock')),
    );
    expect(client.release).toHaveBeenCalledTimes(1);
  });

  it('commits staff updates across users and employees', async () => {
    const client = createClient();
    configureDatabase(client);

    const result = await updateStaff(STAFF_UUID, { employee_role: 'manager', status: 'active' });

    expect(result.outcome).toBe('updated');
    expect(client.query).toHaveBeenCalledWith('BEGIN');
    expect(client.query).toHaveBeenCalledWith('COMMIT');
    expect(client.release).toHaveBeenCalledTimes(1);
  });

  it('checks assignments inside the removal transaction and rolls back a blocked delete', async () => {
    const client = createClient({ assignmentRows: [{ uuid: 'assignment-1' }] });
    configureDatabase(client);

    const result = await removeStaff(STAFF_UUID, 'another-staff');

    expect(result).toEqual({
      outcome: 'has_assignments',
      staffName: 'Staff Member',
      count: 1,
    });
    const statements = client.query.mock.calls.map(([query]) => String(query));
    const beginIndex = statements.indexOf('BEGIN');
    const lockIndex = statements.findIndex((query) => query.includes('FOR UPDATE'));
    const assignmentIndex = statements.findIndex((query) =>
      query.includes('FROM employee_assignments'),
    );
    expect(beginIndex).toBeGreaterThanOrEqual(0);
    expect(lockIndex).toBeGreaterThan(beginIndex);
    expect(assignmentIndex).toBeGreaterThan(lockIndex);
    expect(statements[assignmentIndex]).not.toContain('LIMIT 1');
    expect(client.query).toHaveBeenCalledWith('ROLLBACK');
    expect(client.query).not.toHaveBeenCalledWith('COMMIT');
    expect(statements.some((query) => query.includes('DELETE FROM users'))).toBe(false);
    expect(statements.some((query) => query.includes('DELETE FROM notification'))).toBe(false);
    expect(client.release).toHaveBeenCalledTimes(1);
  });

  // `notification.assignee_uuid` has no delete rule, and every booking request writes one notice
  // per manager, so without this a manager could not be removed once any request came in.
  it("removes the person's own bell notices before the account, in the same transaction", async () => {
    const client = createClient({ staffRole: 'manager' });
    configureDatabase(client);

    const result = await removeStaff(STAFF_UUID, 'another-staff');

    expect(result).toEqual({ outcome: 'removed' });
    const statements = client.query.mock.calls.map(([query]) => String(query));
    const noticeIndex = statements.findIndex((query) => query.includes('DELETE FROM notification'));
    const userIndex = statements.findIndex((query) => query.includes('DELETE FROM users'));
    expect(noticeIndex).toBeGreaterThan(statements.indexOf('BEGIN'));
    expect(userIndex).toBeGreaterThan(noticeIndex);
    expect(statements.indexOf('COMMIT')).toBeGreaterThan(userIndex);
    expect(statements[noticeIndex]).toContain('WHERE assignee_uuid = $1::uuid');
    expect(client.query.mock.calls[noticeIndex]?.[1]).toEqual([STAFF_UUID]);
    expect(client.release).toHaveBeenCalledTimes(1);
  });
});
